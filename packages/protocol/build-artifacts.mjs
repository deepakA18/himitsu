#!/usr/bin/env node
// Turn the snarkjs/circomlib outputs into deployable artifacts.
//
//   1. SpendVerifier.sol      -- the exported verifier, with its three
//                                `sub(gas(), 2000)` calls replaced by literals.
//   2. SpendVerifierStock.sol -- the same file untouched, kept so the A-E suite
//                                can show what the stock export does in a
//                                VERIFY frame (it is rejected: BannedOpcode).
//   3. poseidon.json          -- EVM bytecode + ABI for Poseidon(2) and
//                                Poseidon(1), generated by circomlibjs, so the
//                                pool hashes exactly what the circuit hashes.

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { poseidonContract } from 'circomlibjs'

const HERE = dirname(fileURLToPath(import.meta.url))
const CIRCUITS = join(HERE, 'circuits')
const SRC = join(HERE, 'contracts/src')

// --- 1 & 2: the verifier ---------------------------------------------------

const stock = readFileSync(join(CIRCUITS, 'SpendVerifier.sol'), 'utf8')

// Gas figures sized to each precompile: ECMUL 6000, ECADD 150, PAIRING
// 45000 + 4*34000 = 181000. EIP-150 caps a request above what is available, so
// asking for more than the frame holds is safe.
const GAS_BY_PRECOMPILE = { 7: 20000, 6: 1000, 8: 250000 }
let patched = stock.replace(
  /staticcall\(sub\(gas\(\), 2000\), (\d)/g,
  (_, precompile) => `staticcall(${GAS_BY_PRECOMPILE[precompile]}, ${precompile}`,
)
const remaining = (patched.match(/gas\(\)/g) ?? []).length
if (remaining !== 0) throw new Error(`${remaining} gas() calls left in the verifier`)
if (patched === stock) throw new Error('verifier patch matched nothing')

const header = `// Generated by build-artifacts.mjs from snarkjs' export -- do not edit.
// The ONLY change from the stock export is the gas argument of the three
// precompile staticcalls: \`sub(gas(), 2000)\` -> a literal. During EIP-8141
// mempool validation the GAS opcode is legal only immediately before a *CALL,
// and \`GAS\` followed by \`SUB\` trips the sequential-GAS rule, so the stock
// verifier gets the transaction dropped. See SpendVerifierStock.sol.
`
writeFileSync(join(SRC, 'SpendVerifier.sol'), header + patched.replace('contract Groth16Verifier', 'contract SpendVerifier'))
writeFileSync(
  join(SRC, 'SpendVerifierStock.sol'),
  `// Generated: snarkjs' export, VERBATIM. Kept to demonstrate the rejection.\n` +
    stock.replace('contract Groth16Verifier', 'contract SpendVerifierStock'),
)

// --- 3: the pool WITHOUT the frame-layout check ----------------------------
//
// Generated from GhostPool.sol so the two cannot drift apart. The only
// difference is that `_requireSanctionedLayout()` is not called. attack.mjs
// runs the same attack against both, so the demonstration stays honest: the
// unchecked pool is drained, the real one is not.

const pool = readFileSync(join(SRC, 'GhostPool.sol'), 'utf8')
const CHECK_CALL = '        _requireSanctionedLayout();'
if (!pool.includes(CHECK_CALL)) throw new Error('layout check call not found in GhostPool.sol')
const unchecked_ = pool
  .replace('contract GhostPool {', 'contract GhostPoolUnchecked {')
  .replace(CHECK_CALL, '        // _requireSanctionedLayout();  <-- REMOVED: this is the vulnerable variant')
  .replace(
    '// SPDX-License-Identifier: MIT',
    '// SPDX-License-Identifier: MIT\n// GENERATED from GhostPool.sol by build-artifacts.mjs -- do not edit.\n// The frame-layout check is deliberately absent. Deployed only by attack.mjs,\n// to show what that check is holding back.',
  )
writeFileSync(join(SRC, 'GhostPoolUnchecked.sol'), unchecked_)

// --- 4: the Poseidon hasher ------------------------------------------------

writeFileSync(
  join(HERE, 'poseidon.json'),
  JSON.stringify(
    {
      two: { abi: poseidonContract.generateABI(2), bytecode: poseidonContract.createCode(2) },
      one: { abi: poseidonContract.generateABI(1), bytecode: poseidonContract.createCode(1) },
    },
    null,
    2,
  ),
)

console.log('SpendVerifier.sol      patched (3 gas() sites -> literals)')
console.log('GhostPoolUnchecked.sol generated without the frame-layout check')
console.log('SpendVerifierStock.sol verbatim copy')
console.log('poseidon.json          Poseidon(2) + Poseidon(1) EVM bytecode')
